#!/usr/bin/env python3
"""把靶站静态资源打包成 worker 可直接 import 的 ES 模块。

背景:
  - 课程前端可能托管于 WorkBuddy 云/BaaS 网关(app.workbuddy.host),该网关不服务
    /practice/ 这类静态靶站文件,导致学生 Pyodide 里 requests.get() 拿到的是
    「链接不完整」占位页。
  - 为让学生实操题稳定可取数,把 public/practice/**、public/private/**、
    public/robots.txt 的内容打包进 public/practice-data.js。
  - worker 初始化时用 pyodide.globals.set 注入 Python 全局 _PRACTICE_STATIC,
    并对 requests.Session.request 打补丁:命中预载路径时返回本地 Response。

产出:
  public/practice-data.js
    export const PRACTICE_DATA = { "<相对路径>": "<文本内容>", ... };
"""
import json
import os
import posixpath

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), '..', 'public'))
OUT = os.path.join(ROOT, 'practice-data.js')

# 打包目标:靶站 + 合规教具(robots.txt / private)
INCLUDE_DIRS = ['practice', 'private']
INCLUDE_FILES = ['robots.txt']


def rel(path):
    return posixpath.normpath(os.path.relpath(path, ROOT)).replace('\\', '/')


def main():
    data = {}
    for sub in INCLUDE_DIRS:
        base = os.path.join(ROOT, sub)
        if not os.path.isdir(base):
            continue
        for dirpath, _dirnames, filenames in os.walk(base):
            for fn in filenames:
                fp = os.path.join(dirpath, fn)
                key = rel(fp)
                with open(fp, 'r', encoding='utf-8') as f:
                    data[key] = f.read()
    for fn in INCLUDE_FILES:
        fp = os.path.join(ROOT, fn)
        if os.path.isfile(fp):
            data[rel(fp)] = open(fp, 'r', encoding='utf-8').read()

    # JSON 是合法的 JS 对象字面量,ensure_ascii=False 保留中文可读性
    js = '/* AUTO-GENERATED by scripts/gen-practice-data-bundle.py */\n' \
         'export const PRACTICE_DATA = ' + json.dumps(data, ensure_ascii=False) + ';\n'
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(js)
    print(f'打包 {len(data)} 个资源 -> {OUT} ({len(js)} bytes)')


if __name__ == '__main__':
    main()
